const START_MARKER = "<!-- docs-sync:api-table:start -->";
const END_MARKER = "<!-- docs-sync:api-table:end -->";

export function renderReadmeTable(endpoints) {
  const lines = ["| Method | Endpoint | Description |", "|--------|----------|-------------|"];
  for (const ep of endpoints) {
    lines.push(`| ${ep.method} | \`${ep.path}\` | ${ep.description} |`);
  }
  return lines.join("\n");
}

const NOTICE = "<!-- This table is auto-generated by `npm run docs:sync`. Do not edit by hand. -->";

// Replaces only the content between the marker comments, leaving the rest of README.md untouched.
export function patchReadme(readmeContent, tableMarkdown) {
  const startIdx = readmeContent.indexOf(START_MARKER);
  const endIdx = readmeContent.indexOf(END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    throw new Error(
      `README.md is missing "${START_MARKER}" / "${END_MARKER}" markers — add them around the API table before running docs-sync.`
    );
  }
  const before = readmeContent.slice(0, startIdx + START_MARKER.length);
  const after = readmeContent.slice(endIdx);
  return `${before}\n${NOTICE}\n${tableMarkdown}\n${after}`;
}
